/**
 * Builds server/src/knowledge.generated.ts: everything the assistant may rely on, as one text.
 * Run `npm run knowledge:bundle` after changing anything in knowledge/ (a test checks it).
 */
import { writeFileSync } from 'node:fs';
import { renderKnowledgeBundle } from '../src/ai/knowledge-bundle';

const { text, vocabulary } = renderKnowledgeBundle();
const out = `// GENERATED by \`npm run knowledge:bundle\` from knowledge/ — do not edit by hand.
export const KNOWLEDGE = ${JSON.stringify(text)};
export const VOCABULARY: string[] = ${JSON.stringify(vocabulary)};
`;
writeFileSync(new URL('../server/src/knowledge.generated.ts', import.meta.url), out);
console.log(`server/src/knowledge.generated.ts: ${(text.length / 1024).toFixed(0)} kB knowledge`);
